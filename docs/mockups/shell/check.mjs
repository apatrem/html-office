// Interaction checks for the mock-ups (menus, submenus, panels, focus return, tabs, overflow).
// Usage (repository root): node docs/mockups/shell/check.mjs
import { chromium } from "playwright";
import assert from "node:assert/strict";
const base = new URL("./", import.meta.url).href;
const b = await chromium.launch(); const errs = [];
const page = async (f, w = 1440) => { const p = await (await b.newContext({ viewport: { width: w, height: 900 } })).newPage(); p.on("pageerror", (e) => errs.push(f + ": " + e.message)); await p.goto(base + f); return p; };
const active = (p) => p.evaluate(() => document.activeElement?.getAttribute("aria-label") || document.activeElement?.textContent.trim());
let p = await page("a-data.html#settings");
await p.locator('[data-set-theme="green"]').first().click();
assert.equal(await p.evaluate(() => document.documentElement.dataset.theme), "green", "theme click works");
await p.locator('[data-set-font="georgia"]').first().click();
assert.equal(await p.evaluate(() => document.documentElement.dataset.font), "georgia", "font click works");
p = await page("a-data.html#none"); await p.getByRole("button", { name: "Styles", exact: true }).focus(); await p.keyboard.press("Enter");
assert.equal(await p.evaluate(() => document.body.dataset.panel), "styles");
await p.keyboard.press("Escape");
assert.equal(await active(p), "Styles", "Escape returns focus to the panel toggle");
await p.locator('[role=menubar] .mb').first().focus(); await p.keyboard.press("ArrowRight");
assert.equal(await active(p), "Edit", "menubar arrows");
await p.keyboard.press("ArrowDown");
assert.ok(await p.locator("#m-data-edit").isVisible(), "ArrowDown opens");
await p.keyboard.press("Escape");
p = await page("a-data.html#none", 375); await p.getByRole("button", { name: "Menu" }).click();
await p.locator("#m-main").getByRole("menuitem", { name: "Format" }).click();
assert.ok(await p.locator("#m-data-format").isVisible(), "☰ › Format opens");
await p.locator("#m-data-format").getByRole("menuitem", { name: /^Borders/ }).click();
assert.ok(await p.locator("#m-borders").isVisible(), "Format › Borders opens");
p = await page("a-slides.html#none");
await p.locator('[role=menubar] .mb', { hasText: "Insert" }).click();
await p.locator("#m-slides-insert").getByRole("menuitem", { name: /^Shape/ }).click();
assert.ok(await p.locator("#m-shape").isVisible(), "Insert › Shape opens");
assert.equal(await p.locator("#m-newslide [role=menuitem]").count(), 12, "12 layouts");
p = await page("b-data.html#none");
const stop = await p.evaluate(() => { const b = document.querySelector('#rp-home [role=toolbar] button[tabindex="0"]'); return b && b.offsetParent !== null; });
assert.ok(stop, "B toolbar tab stop is visible");
await p.getByRole("tab", { name: "Document" }).click();
assert.equal(await p.locator("#rp-document").isVisible(), true, "tab click works");
p = await page("a-data.html#none", 375);
const before = await p.evaluate(() => document.querySelector(".tscroll").scrollLeft);
await p.locator(".tbar .ovr").first().click(); await p.waitForTimeout(500);
assert.ok(await p.evaluate(() => document.querySelector(".tscroll").scrollLeft) > before, "overflow arrow scrolls");
p = await page("c-text.html#none");
await p.getByRole("button", { name: "More commands" }).click();
await p.locator("#m-more").getByRole("menuitem", { name: /^Table/ }).click();
assert.ok(await p.locator("#m-table").isVisible(), "Text table submenu");
// Default panel open, then another panel from a menu: Escape returns to that menu's trigger.
p = await page("a-data.html");
await p.locator("[role=menubar] .mb", { hasText: "File" }).click();
await p.locator("#m-data-file").getByRole("menuitem", { name: "Document settings…" }).click();
assert.equal(await p.evaluate(() => document.body.dataset.panel), "settings");
await p.keyboard.press("Escape");
assert.equal(await active(p), "File", "focus returns after switching panels from a menu");
assert.deepEqual(errs, []);
console.log("all mock-up checks pass");
await b.close();
