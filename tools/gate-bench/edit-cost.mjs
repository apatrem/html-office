#!/usr/bin/env node
// Token cost of an edit on the two distributed example decks (ADR-016 §8, step 2): what an
// assistant has to read before it changes a deck. Writes docs/gate/EDIT-TOKEN-COST.md.
//   node tools/gate-bench/edit-cost.mjs           regenerate the table
//   node tools/gate-bench/edit-cost.mjs --check   fail if the committed table is stale
// Token counts are a proxy: gpt-tokenizer (o200k_base), the tokenizer already pinned in
// tools/engine-assessment. Install it once with: npm ci --prefix tools/engine-assessment --ignore-scripts
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { createRequire } from 'node:module';
import { pathToFileURL, fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const SKILL = path.join(ROOT, 'plugin/skills/html-slides');
const OUT = path.join(ROOT, 'docs/gate/EDIT-TOKEN-COST.md');
const DECKS = ['community-garden.html', 'catalogue.html'];

const require = createRequire(path.join(ROOT, 'tools/engine-assessment/package.json'));
let encode, tokenizerVersion;
try {
  ({ encode } = await import(pathToFileURL(require.resolve('gpt-tokenizer/encoding/o200k_base')).href));
  tokenizerVersion = require('gpt-tokenizer/package.json').version;
} catch {
  console.error('Error: gpt-tokenizer is not installed. Run: npm ci --prefix tools/engine-assessment --ignore-scripts');
  process.exit(1);
}
const tokens = text => encode(text).length;
const n = value => value.toLocaleString('en-US');

function measure(name) {
  const file = path.join(SKILL, 'examples', name);
  const html = fs.readFileSync(file, 'utf8');
  const stage = fs.mkdtempSync(path.join(os.tmpdir(), 'gate-extract-'));
  try {
    // Relative paths: the extract's header comment names them, and the count must not depend on a temporary folder's name.
    fs.copyFileSync(file, path.join(stage, name));
    execFileSync(process.execPath, [path.join(SKILL, 'tools/deck.mjs'), 'extract', name, '--out', 'x'], { cwd: stage, stdio: 'ignore' });
    const content = fs.readFileSync(path.join(stage, 'x/content.html'), 'utf8');
    const guide = html.match(/<template\b[^>]*\bid="html-slides-guide"[^>]*>([\s\S]*?)<\/template>/);
    if (!guide) throw new Error(`${name} has no embedded guide`);
    return { name, slides: (content.match(/<section\b[^>]*\bclass="slide\b/g) ?? []).length, bytes: Buffer.byteLength(html), fileTokens: tokens(html),
      extractBytes: Buffer.byteLength(content), extractTokens: tokens(content), guideBytes: Buffer.byteLength(guide[1]), guideTokens: tokens(guide[1]) };
  } finally { fs.rmSync(stage, { recursive: true, force: true }); }
}

const rows = DECKS.map(measure);
const version = fs.readFileSync(path.join(SKILL, 'assets/VERSION'), 'utf8').trim();
const text = `# Token cost of an edit on the example decks

Generated by \`node tools/gate-bench/edit-cost.mjs\`; do not edit by hand (\`--check\` fails on a stale copy). Part of the measurement kit of [ADR-016](../decisions/016-slides-go-stop-gate.md) §8.

Before it changes a deck, an assistant reads the deck's content. The skill tells it to read the output of \`deck.mjs extract\` (the content zone, without cached chart pictures or embedded images) and, when present, the guide embedded in the file. The table gives the size of each for the two decks distributed with the skill (html-slides ${version}).

| Deck | Slides | Whole file | Whole file, tokens | \`extract\` output | \`extract\` output, tokens | Embedded guide | Embedded guide, tokens |
| --- | --- | --- | --- | --- | --- | --- | --- |
${rows.map(r => `| \`${r.name}\` | ${r.slides} | ${n(r.bytes)} bytes | ${n(r.fileTokens)} | ${n(r.extractBytes)} bytes | ${n(r.extractTokens)} | ${n(r.guideBytes)} bytes | ${n(r.guideTokens)} |`).join('\n')}

- **Tokens are a proxy.** They are counted with \`gpt-tokenizer\` ${tokenizerVersion}, encoding \`o200k_base\`, the tokenizer pinned in \`tools/engine-assessment\`. It is OpenAI's encoding, not Claude's: Claude's own count for the same text differs. The figures compare the three readings with each other; the measured cost of an edit is the usage that the editing sessions of the bench report.
- **Whole file** is what reading the \`.html\` directly would cost. Most of it is the editor engine (${n(fs.statSync(path.join(SKILL, 'assets/engine.js')).size)} bytes); no step of the skill asks for it.
- **\`extract\` output** is what an edit needs: about ${Math.round(rows[0].extractTokens / rows[0].slides)} tokens per slide for \`${rows[0].name}\` and ${Math.round(rows[1].extractTokens / rows[1].slides)} for \`${rows[1].name}\`.
- **Embedded guide** is the same text in every deck of a given engine version. An assistant that already has the skill does not need to read it; one that only has the file does, once.
- The skill's own instructions and references, and the screenshots the assistant looks at before and after an edit, are not in this table: they are part of the measured sessions.
`;

if (process.argv.includes('--check')) {
  if (!fs.existsSync(OUT) || fs.readFileSync(OUT, 'utf8') !== text) { console.error(`${path.relative(ROOT, OUT)} is stale: run node tools/gate-bench/edit-cost.mjs`); process.exit(1); }
  console.log(`${path.relative(ROOT, OUT)} is current`);
} else {
  fs.writeFileSync(OUT, text);
  console.log(`Wrote ${path.relative(ROOT, OUT)}`);
}
