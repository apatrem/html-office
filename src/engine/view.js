// Layout inspired by Bento: a top bar (undo, insert, PDF, save),
// a context bar right below it (slide, or selected element), thumbnails on the left,
// and a pill at the bottom right (edit, present) outside edit mode.
function button(parent, icon, label, title, fn, cls = '') {
  const b = ui('button', cls);
  b.innerHTML = (icon || '') + (label ? '<span class="hs-lbl"></span>' : '');
  if (label) b.querySelector('.hs-lbl').textContent = label;
  b.title = title;
  b.onclick = e => { e.preventDefault(); fn(b); };
  parent.appendChild(b);
  return b;
}
